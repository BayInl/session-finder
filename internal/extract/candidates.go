const (
	StatusDetected  = "detected"
	StatusDraft     = "draft"
	StatusInReview  = "in_review"
	StatusApproved  = "approved"
	StatusPublished = "published"
	StatusRejected  = "rejected"
	StatusDeferred  = "deferred"
	StatusFailed    = "failed"
	StatusDisabled  = "disabled"
	StatusDeleted   = "deleted"
)

const (
	ActionCreate     = "create"
	ActionTransition = "transition"
	ActionDelete     = "delete"
	ActionRestore    = "restore"
)

var (
	ErrNotFound           = errors.New("candidate not found")
	ErrInvalidStatus      = errors.New("invalid candidate status")
	ErrInvalidTransition  = errors.New("invalid candidate status transition")
	ErrCandidateDeleted   = errors.New("candidate is deleted")
	ErrCandidateNotDelete = errors.New("candidate is not deleted")
)

// DefaultDBPath is the database used by the index command unless --db is set.
// Candidate storage deliberately opens this path independently from internal/index.
var DefaultDBPath = filepath.Join(userHome(), ".cache", "session-finder", "index.db")

var validStatuses = map[string]struct{}{
	StatusDetected: {}, StatusDraft: {}, StatusInReview: {}, StatusApproved: {},
	StatusPublished: {}, StatusRejected: {}, StatusDeferred: {}, StatusFailed: {},
	StatusDisabled: {}, StatusDeleted: {},
}

// transitions lists deliberate state-machine edges. Deleted candidates are
// restored through Restore, so they have no ordinary outgoing edge.
var transitions = map[string]map[string]struct{}{
	StatusDetected: {
		StatusDraft: {}, StatusDisabled: {}, StatusDeleted: {},
	},
	StatusDraft: {
		StatusInReview: {}, StatusDisabled: {}, StatusDeleted: {},
	},
	StatusInReview: {
		StatusApproved: {}, StatusRejected: {}, StatusDeferred: {}, StatusFailed: {}, StatusDisabled: {}, StatusDeleted: {},
	},
	StatusApproved: {
		StatusPublished: {}, StatusDisabled: {}, StatusDeleted: {},
	},
	StatusPublished: {
		StatusDisabled: {}, StatusDeleted: {},
	},
	StatusRejected: {
		StatusDraft: {}, StatusDeferred: {}, StatusDisabled: {}, StatusDeleted: {},
	},
	StatusDeferred: {
		StatusDraft: {}, StatusInReview: {}, StatusDisabled: {}, StatusDeleted: {},
	},
	StatusFailed: {
		StatusDraft: {}, StatusInReview: {}, StatusDeferred: {}, StatusDisabled: {}, StatusDeleted: {},
	},
	StatusDisabled: {
		StatusDraft: {}, StatusDeleted: {},
	},
	StatusDeleted: {},
}

// CanTransition reports whether a status change is accepted by the state machine.
func CanTransition(from, to string) bool {
	if !ValidStatus(from) || !ValidStatus(to) || from == StatusDeleted {
		return false
	}
	_, ok := transitions[from][to]
	return ok
}

// ValidStatus reports whether status is one of the persisted candidate states.
func ValidStatus(status string) bool {
	_, ok := validStatuses[status]
	return ok
}

// ValidateTransition returns a descriptive error for an invalid state change.
func ValidateTransition(from, to string) error {
	if !ValidStatus(from) || !ValidStatus(to) {
		return fmt.Errorf("%w: %q -> %q", ErrInvalidStatus, from, to)
	}
	if !CanTransition(from, to) {
		return fmt.Errorf("%w: %q -> %q", ErrInvalidTransition, from, to)
	}
	return nil
}

